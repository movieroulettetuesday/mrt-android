/** cloudkit.json + stats.json pollTally / ratingAggregate (generated by running iOS RouletteCore). */
class CommunityVectorsTest {
    private val v = SharedVectors.load("cloudkit.json")

    @Test
    fun containerAndDatabase() {
        assertEquals(v.str("container"), CommunityConfig.CONTAINER)
        assertEquals("public", v.str("database"))
    }

    @Test
    fun sha256AndSafeComponent() {
        for (c in v.arr("sha256").objs()) assertEquals(c.str("input"), c.str("sha256hex"), Sha256.hex(c.str("input")!!))
        for (c in v.arr("safeComponent").objs()) assertEquals(c.str("input"), c.str("expected"), CommunityRecordNames.safeComponent(c.str("input")!!))
    }

    @Test
    fun recordNamesMatchIosByteForByte() {
        for (c in v.arr("voteRecordName").objs()) {
            assertEquals(c.str("expected"), CommunityRecordNames.vote(c.str("pollId")!!, c.str("userRecordName")!!))
        }
        for (c in v.arr("ratingRecordName").objs()) {
            assertEquals(c.str("expected"), CommunityRecordNames.rating(c.str("movieId")!!, c.str("userRecordName")!!))
        }
        for (c in v.arr("ratingFields").objs()) assertEquals(c.int("starsFieldWritten"), HalfStars.roundedStars(c.int("halfStars")!!))
    }

    private fun options(o: JsonObject) = o.arr("options").objs().map { PollOption(it.str("id")!!, it.str("label")!!) }

    @Test
    fun defaultPollsAndOverrides() {
        val dp = v.obj("defaultPolls")
        val hosts = dp["hosts"]!!.strings()
        for (c in dp.arr("cases").objs()) {
            val guid = c.str("episodeGuid")!!
            val poll = PollFactory.defaultPoll(guid, hosts)
            assertEquals(guid, c.str("kind"), PollFactory.defaultKind(guid).name.replaceFirstChar(Char::lowercase))
            assertEquals(c.str("pollId"), poll.id)
            assertEquals(c.str("question"), poll.question)
            assertEquals(options(c), poll.options)
        }
        for (c in dp.arr("argumentHostEdgeCases").objs()) {
            val poll = PollFactory.defaultPoll(c.str("episodeGuid")!!, c["hosts"]!!.strings())
            assertEquals(options(c), poll.options)
        }
        val po = v.obj("pollOverrides")
        val overrides = PollOverrides.decode(po["input"].toString())!!
        for (c in po.arr("cases").objs()) {
            val poll = PollFactory.poll(c.str("episodeGuid")!!, hosts, overrides)
            assertEquals(c.str("pollId"), poll.id)
            assertEquals(c.str("question"), poll.question)
            assertEquals(options(c), poll.options)
        }
    }

    @Test
    fun suggestionRecordShape() {
        val s = v.obj("suggestionRecord")
        assertEquals(CommunityRecordNames.SUGGESTION_RECORD_TYPE, s.str("recordType"))
        assertEquals(listOf("title", "category", "note", "creditName", "appVersion"), s["fields"]!!.strings())
    }

    @Test
    fun pollTallyAndRatingAggregate() {
        val stats = SharedVectors.load("stats.json")
        for (c in stats.arr("pollTally").objs()) {
            val ids = c["options"]!!.strings()
            val poll = PollDefinition("p", "g", "q", ids.map { PollOption(it, it) })
            val r = PollResults.tally(poll, c["votes"]!!.strings())
            val e = c.obj("expected")
            assertEquals(e.int("total"), r.total)
            assertEquals(e["leaders"]!!.strings(), r.leaders.map { it.id })
            e.arr("rows").objs().forEachIndexed { i, row ->
                assertEquals(row.str("option"), r.rows[i].option.id)
                assertEquals(row.int("count"), r.rows[i].count)
                assertClose("fraction", row.dbl("fraction")!!, r.rows[i].fraction, 1e-9)
            }
        }
        for (c in stats.arr("ratingAggregate").objs()) {
            val half = (c["halfStars"] as JsonArray).map { (it as JsonPrimitive).int }
            val a = RatingAggregate.fromHalfStars(half)
            val e = c.obj("expected")
            assertEquals(e.int("count"), a.count)
            assertEquals((e["histogram"] as JsonArray).map { (it as JsonPrimitive).int }, a.histogram)
            if (e.dbl("average") == null) {
                assertNull(a.average); assertNull(a.averageToHalf); assertNull(a.averageHalfStars)
            } else {
                assertClose("avg", e.dbl("average")!!, a.average!!, 1e-9)
                assertClose("half", e.dbl("averageToHalf")!!, a.averageToHalf!!, 1e-9)
                assertEquals(e.int("averageHalfStars"), a.averageHalfStars)
            }
        }
    }

    @Test
    fun timedCacheAndBackoff() {
        var now = 0L
        val cache = TimedCache<String, Int>(60_000, maxEntries = 2) { now }
        cache.insert("a", 1); now = 10; cache.insert("b", 2); now = 20; cache.insert("c", 3)
        assertEquals(2, cache.size)
        assertNull(cache.staleValue("a")) // oldest evicted
        now = 60_015
        assertEquals(3, cache.value("c")) // 59.995 s old
        assertNull(cache.value("b")) // expired
        assertEquals(2, cache.staleValue("b"))

        val backoff = CommunityBackoff { now }
        backoff.note(CommunityError.Busy(null))
        assertEquals(10, backoff.secondsRemaining())
        backoff.note(CommunityError.Busy(2)) // never shortens
        assertEquals(10, backoff.secondsRemaining())
        assertEquals(300L, CommunityError.Busy(9999).backoffSeconds)
        assertEquals(1L, CommunityError.Busy(0).backoffSeconds)
        assertEquals(60L, CommunityError.QuotaExceeded().backoffSeconds)
        assertNull(CommunityError.Offline().backoffSeconds)
        now += 10_000
        assertNull(backoff.secondsRemaining())
    }
}
